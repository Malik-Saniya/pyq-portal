export const MU_SUBJECTS = COURSE_DEFS.flatMap((course) =>
  Object.entries(course.syllabus).flatMap(([sem, rows]) =>
    rows.map(([nepCategory, name, extra = {}]) => {
      const semester = Number(sem);
      const slug = `${course.slug}-s${semester}-${slugify(name)}`;
      return {
        id: `subj-mu-${slug}`,
        slug,
        name,
        code: null,
        level: "degree",
        source: SOURCE,
        universitySlug: MU_UNIVERSITY.slug,
        courseSlug: course.slug,
        semester,
        scheme: SCHEME,
        nepCategory,
        majorType: extra.type ?? null,
        specialization: extra.spec ?? null,
        discipline: extra.discipline ?? null,
        note: extra.note ?? null,
        isPractical: nepCategory === "PRACTICAL",
      };
    })
  )
);